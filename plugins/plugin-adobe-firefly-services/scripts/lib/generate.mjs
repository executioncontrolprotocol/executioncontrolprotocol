/**
 * @param {string} dir
 * @param {string[]} [acc]
 */
function walkFiles(dir, acc = []) {
  if (!statSync(dir, { throwIfNoEntry: false })?.isDirectory()) return acc
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) walkFiles(p, acc)
    else if (/\.(json|ya?ml)$/i.test(name)) acc.push(p)
  }
  return acc
}

/**
 * Apply path-array overlays onto a document.
 * @param {any} doc
 * @param {{ path: string[], value: unknown }[]} patches
 */
export function applyOverlays(doc, patches) {
  for (const patch of patches) {
    let cur = doc
    const parts = patch.path
    for (let i = 0; i < parts.length - 1; i++) {
      const key = parts[i]
      if (cur[key] == null || typeof cur[key] !== "object") cur[key] = {}
      cur = cur[key]
    }
    cur[parts[parts.length - 1]] = patch.value
  }
}

/**
 * Load every vendored spec grouped by family, overlays applied.
 * @param {string} openapiDir
 * @param {{ families?: string[] }} [options] Restrict to these families.
 * @returns {Map<string, FamilySpec[]>}
 */
export function loadFamilySpecs(openapiDir, options = {}) {
  const overlayPath = join(openapiDir, "overlays", "schema-fixes.json")
  /** @type {Record<string, { path: string[], value: unknown }[]>} */
  let overlays = {}
  try {
    overlays = JSON.parse(readFileSync(overlayPath, "utf8"))
  } catch {
    overlays = {}
  }
  /** @type {Map<string, FamilySpec[]>} */
  const families = new Map()
  for (const file of walkFiles(openapiDir)) {
    const rel = relative(openapiDir, file).replace(/\\/g, "/")
    if (rel.startsWith("overlays/")) continue
    const family = familyForSpec(rel)
    if (SKIPPED_FAMILIES.has(family)) continue
    if (options.families && !options.families.includes(family)) continue
    const text = readFileSync(file, "utf8")
    const doc = /\.ya?ml$/i.test(file) ? parseYaml(text) : JSON.parse(text)
    if (overlays[rel]) applyOverlays(doc, overlays[rel])
    const list = families.get(family) ?? []
    list.push({ rel, doc })
    families.set(family, list)
  }
  return new Map([...families.entries()].sort(([a], [b]) => (a < b ? -1 : 1)))
}

/**
 * @param {any} doc
 * @param {string} ref
 */
function resolveRef(doc, ref) {
  if (!ref.startsWith("#/")) throw new Error(`External $ref not supported: ${ref}`)
  let cur = doc
  for (const p of ref.slice(2).split("/")) cur = cur?.[p]
  return cur
}

/**
 * @param {any} doc
 * @param {any} schema
 */
function isJsonContentTypeHeader(doc, schema) {
  let current = schema
  const seen = new Set()
  while (current?.$ref) {
    if (seen.has(current.$ref)) return false
    seen.add(current.$ref)
    current = resolveRef(doc, current.$ref)
  }
  const values = current?.enum
  if (!Array.isArray(values) || values.length !== 1) return false
  return String(values[0]).toLowerCase() === "application/json"
}

/**
 * @param {string} contentType
 */
function isJsonMediaType(contentType) {
  const lower = contentType.toLowerCase()
  return lower === "application/json" || lower.endsWith("+json") || lower === "*/*"
}

/**
 * Capability key for an operation: family prefix + kebab operationId (or method + path).
 * @param {string} family
 * @param {string} operationId
 * @param {string} method
 * @param {string} path
 * @param {string} [specRel] OpenAPI path relative to openapi/ (for spec-scoped id remaps).
 */
export function capabilityName(family, operationId, method, path, specRel) {
  let suffix
  const specKey = specRel && operationId ? `${specRel}:${operationId}` : ""
  if (specKey && OPERATION_SPEC_ID_REMAP[specKey]) {
    suffix = OPERATION_SPEC_ID_REMAP[specKey]
  } else if (operationId) {
    suffix = OPERATION_ID_REMAP[operationId] ?? toKebab(operationId)
  } else {
    const fromPath = path
      .replace(/^\//, "")
      .replace(/\{([^}]+)\}/g, "by-$1")
      .replace(/\//g, "-")
    suffix = toKebab(`${method}-${fromPath}`)
  }
  return `${family}-${suffix}`
    .replace(/[^a-z0-9-]+/gi, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase()
}

/**
 * @typedef {object} BuiltInput
 * @property {string[]} fields `key: expr` lines for the top-level accepts object.
 * @property {{ path: string[], query: string[], headers: string[], body: string[] }} parameters
 * @property {string | undefined} bodySchema Zod expression for the full request body.
 * @property {boolean} bodyRequired
 * @property {boolean} defaultCaiClaimVersion
 * @property {string[]} keys Top-level accepts keys.
 * @property {string | undefined} skip Reason the operation cannot be generated.
 */

/**
 * Build the flat capability input for one operation. Path, query, header and JSON-body fields
 * are hoisted to top-level keys; an optional `body` carries the rest of the JSON document.
 * @param {any} operation
 * @param {any} doc
 * @param {ZodEmitter} emitter Input-mode emitter.
 * @param {string} context
 * @param {any[]} [pathItemParameters] Parameters declared on the path item.
 * @returns {BuiltInput}
 */
export function buildInput(operation, doc, emitter, context, pathItemParameters = []) {
  /** @type {BuiltInput["parameters"]} */
  const parameters = { path: [], query: [], headers: [], body: [] }
  const claimed = new Set()
  /** @type {string[]} */
  const fields = []
  /** @type {string[]} */
  const keys = []

  /**
   * @param {string} name
   * @param {string} where
   */
  const claim = (name, where) => {
    if (RESERVED_INPUT_FIELDS.has(name) || claimed.has(name)) {
      throw new Error(`Capability input field collision: ${JSON.stringify(name)} at ${where}`)
    }
    claimed.add(name)
    keys.push(name)
  }

  /**
   * @param {string} name
   * @param {string} expr
   * @param {boolean} optional
   * @param {string} description
   */
  const push = (name, expr, optional, description) => {
    let out = optional ? `${expr}.optional()` : expr
    if (description) out = `${out}.describe(${JSON.stringify(description)})`
    fields.push(`  ${objectKey(name)}: ${indentContinuation(out)}`)
  }

  /** @type {Map<string, any>} */
  const merged = new Map()
  for (const raw of [...pathItemParameters, ...(operation.parameters ?? [])]) {
    const p = raw?.$ref ? resolveRef(doc, raw.$ref) : raw
    if (!p?.name || !p.in) continue
    merged.set(`${p.in}:${p.name}`, p)
  }

  for (const p of merged.values()) {
    if (p.in !== "path" && p.in !== "query" && p.in !== "header") continue
    const schema = p.schema ?? { type: "string" }
    if (p.in === "header") {
      const lower = String(p.name).toLowerCase()
      if (AUTH_HEADERS.has(lower)) continue
      if (lower === "content-type" && isJsonContentTypeHeader(doc, schema)) continue
    }
    claim(p.name, `${context}.${p.in}.${p.name}`)
    const required = p.in === "path" ? true : Boolean(p.required)
    const field = emitter.fieldZod([schema], `${context}.${p.in}.${p.name}`, p.description)
    push(p.name, field.expr, !required, field.description)
    if (p.in === "path") parameters.path.push(p.name)
    else if (p.in === "query") parameters.query.push(p.name)
    else parameters.headers.push(p.name)
  }

  let bodySchema
  let bodyRequired = false
  let defaultCaiClaimVersion = false
  if (operation.requestBody) {
    const rb = operation.requestBody.$ref ? resolveRef(doc, operation.requestBody.$ref) : operation.requestBody
    const content = rb?.content ?? {}
    const types = Object.keys(content)
    const jsonType = types.find(isJsonMediaType)
    if (!jsonType) {
      return {
        fields,
        parameters,
        bodySchema: undefined,
        bodyRequired: false,
        defaultCaiClaimVersion: false,
        keys,
        skip: `non-JSON request body (${types.join(", ") || "no content"}); needs file-reference upload support`,
      }
    }
    const schema = content[jsonType]?.schema
    bodyRequired = rb?.required !== false
    if (schema) {
      bodySchema = emitter.schemaToZod(schema, `${context}.body`)
      const flat = emitter.flattenObject(schema)
      if (flat && flat.properties.size > 0) {
        for (const [name, candidates] of flat.properties) {
          claim(name, `${context}.body.${name}`)
          const field = emitter.fieldZod(candidates, `${context}.body.${name}`)
          push(name, field.expr, true, field.description)
          parameters.body.push(name)
        }
        defaultCaiClaimVersion = flat.properties.has("caiClaimVersion")
        push("body", "z.looseObject({})", true, BODY_DESCRIPTION)
      } else {
        push("body", bodySchema, !bodyRequired, cleanDescription(rb?.description))
      }
      keys.push("body")
    }
  }

  return { fields, parameters, bodySchema, bodyRequired, defaultCaiClaimVersion, keys, skip: undefined }
}

/**
 * @param {any} doc
 */
function serverUrl(doc) {
  const server = doc.servers?.[0]?.url
  if (typeof server !== "string" || !/^https?:\/\//.test(server)) return ""
  return server.replace(/\/+$/, "")
}

/**
 * True when the operation's success responses carry content but none of it is JSON.
 * @param {any} operation
 * @param {any} doc
 */
function hasNonJsonSuccessOnly(operation, doc) {
  const responses = operation.responses ?? {}
  let sawContent = false
  for (const [code, resp] of Object.entries(responses)) {
    if (!/^2/.test(code)) continue
    const resolved = /** @type {any} */ (resp)?.$ref ? resolveRef(doc, /** @type {any} */ (resp).$ref) : resp
    const types = Object.keys(resolved?.content ?? {})
    if (types.length === 0) continue
    sawContent = true
    if (types.some((t) => isJsonMediaType(t) || t === "application/problem+json")) return false
  }
  return sawContent
}

/**
 * @param {string} kebab
 */
function humanizeKebab(kebab) {
  return kebab
    .split("-")
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ")
}

/**
 * @param {string} family
 */
function familyLabel(family) {
  return FAMILY_LABELS[family] ?? humanizeKebab(family)
}

/**
 * Plain-text projections from operation-name heuristics.
 * @param {string} name
 * @param {"async-submit" | "sync"} opClass
 * @returns {string[]}
 */
export function deriveProjections(name, opClass) {
  const lower = name.toLowerCase()
  if (/list|voices|avatars|presets|models|tags|versions|scripts|languages|fonts/.test(lower) && opClass === "sync") {
    return ["Keep each listed item's id and display name so a later step can select one; drop the rest."]
  }
  if (/describe|manifest|document-info|details|info/.test(lower)) {
    return [
      "Read the document facts the next step needs (layer or page names, sizes, ids) instead of carrying the whole result forward.",
    ]
  }
  if (/generate|export|rendition|render|create|fill|expand|upload|composite|edit|crop|actions|merge|upscale|dub|transcribe|trace|reframe|assemble|convert|compose/.test(lower)) {
    return [
      "Keep the output asset URLs or storage references for download or the next edit step; the job envelope is already removed.",
    ]
  }
  return ["Take the ids or asset URLs the next step needs from the response."]
}

/**
 * Agent-facing metadata for one operation.
 * @param {any} operation
 * @param {string} family
 * @param {string} name
 * @param {"async-submit" | "sync"} opClass
 */
export function deriveMetadata(operation, family, name, opClass) {
  const label = familyLabel(family)
  const override = METADATA_OVERRIDES[name] ?? {}
  const phrase =
    override.summary ??
    (name === "photoshop-actions"
      ? "Run Photoshop actions or a UXP script on a document"
      : formatSummaryPhrase(operation, name, cleanDescription))
  const summary = phrase.includes("(Adobe ")
    ? phrase
    : phrase.endsWith(".")
      ? phrase
      : name === "photoshop-actions"
        ? phrase.endsWith(".")
          ? phrase
          : `${phrase}.`
        : `${phrase.replace(/\.$/, "")} (Adobe ${label}).`
  let description = override.description ?? (cleanDescription(operation.description ?? "", 1200) || summary)
  if (opClass === "async-submit" && !override.description) {
    description = `${description} The step submits the Adobe job, waits for it to finish and returns the job result, not the job id.`
  }

  const useCases = override.useCases ?? deriveDefaultUseCases(operation, name, label, phrase.replace(/\.$/, ""))

  const base = { summary, description, useCases, projections: override.projections ?? deriveProjections(name, opClass) }
  return base
}

/**
 * Generate one family's modules.
 * @param {string} family
 * @param {FamilySpec[]} specs
 */
export function generateFamily(family, specs) {
  /** @type {Map<string, any>} */
  const components = new Map()
  for (const { doc } of specs) {
    for (const [name, schema] of Object.entries(doc.components?.schemas ?? {})) components.set(name, schema)
  }
  const input = new ZodEmitter(components, { mode: "input" })
  const output = new ZodEmitter(components, { mode: "output" })

  /** @type {string[]} */
  const errors = []
  /** @type {{ name: string, reason: string }[]} */
  const skipped = []
  /** @type {any[]} */
  const ops = []
  const seen = new Set()

  for (const { rel, doc } of specs) {
    const server = serverUrl(doc)
    for (const [path, item] of Object.entries(doc.paths ?? {})) {
      for (const method of HTTP_METHODS) {
        const operation = /** @type {any} */ (item)?.[method]
        if (!operation) continue
        const operationId = operation.operationId || ""
        let name = capabilityName(family, operationId, method, path, rel)
        const context = `${rel}:${method.toUpperCase()} ${path}`
        const opClass = classifyOperation({
          path,
          operationId,
          method: method.toUpperCase(),
          responseCodes: Object.keys(operation.responses ?? {}),
          acceptSchemaName: acceptSchemaNameForOperation(operation, doc),
          opName: name,
        })
        if (opClass === "status-cancel") continue
        if (seen.has(name)) name = `${name}-${toKebab(path.split("/").filter(Boolean).pop() || "x")}`
        if (seen.has(name)) continue
        if (name.length > 64) {
          skipped.push({ name, reason: "capability key longer than 64 characters" })
          continue
        }

        let built
        try {
          built = buildInput(operation, doc, input, `${context}.input`, /** @type {any} */ (item).parameters)
        } catch (error) {
          errors.push(error instanceof Error ? error.message : String(error))
          continue
        }
        if (built.skip) {
          skipped.push({ name, reason: built.skip })
          continue
        }
        if (opClass === "sync" && hasNonJsonSuccessOnly(operation, doc)) {
          skipped.push({ name, reason: "non-JSON response body; needs artifact download support" })
          continue
        }
        if (!server) {
          errors.push(`${context}: spec has no absolute server URL`)
          continue
        }

        const resolved = resolveOutputForOperation(name, opClass, operation, doc)
        const bodyFieldSchemas = collectBodyFieldSchemas(operation, doc)
        const acceptShape = reshapeCapabilityAccepts(built, operation, doc, bodyFieldSchemas)
        const shaped = applyProductShape(name, opClass, operation, doc, resolved, output, `${context}.output`)
        const returns = shaped.returnsZod
        if (resolved.unknownFinal) errors.push(`${context}: async operation ${name} has no final output mapping`)

        seen.add(name)
        ops.push({
          name,
          method: method.toUpperCase(),
          path,
          server,
          opClass,
          built,
          returns,
          usesFileRef: shaped.usesFileRef || acceptShape.usesFileRef,
          productShape: shaped.productShape,
          fileRefBodyFields: acceptShape.usesFileRef ? [...built.parameters.body] : [],
          defaultManifestOutputs: Boolean(resolved.defaultManifestOutputs),
          metadata: deriveMetadata(operation, family, name, opClass),
        })
      }
    }
  }
  errors.push(...input.errors, ...output.errors)
  ops.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))

  const rels = specs.map((s) => s.rel).join(", ")
  const exportName = `${toCamel(family)}Capabilities`

  const schemaLines = [`/* ${GENERATED_BANNER} */`, `/* Source: ${rels} */`, `import { z } from "zod"`, ``]
  for (const [emitter, mode] of [
    [input, "request (closed)"],
    [output, "response (open)"],
  ]) {
    for (const [ident, label, expr] of /** @type {ZodEmitter} */ (emitter).components()) {
      schemaLines.push(`/**`, ` * ${label}, ${mode}.`, ` * @category Generated`, ` */`)
      schemaLines.push(`export const ${ident}: z.ZodType = ${resolveRefs(expr, "")}`, ``)
    }
  }
  let schemasTs = `${schemaLines.join("\n").trimEnd()}\n`
  const nestedPatch = patchNestedFileRefSchemas(schemasTs, family)
  schemasTs = nestedPatch.text

  const capLines = []
  let capUsesSchemas = false
  let capUsesFileRef = nestedPatch.nestedFileRefFields > 0
  for (const op of ops) {
    const acceptsRaw = op.built.fields.length ? `z.strictObject({\n${op.built.fields.join(",\n")}\n})` : "z.strictObject({})"
    const accepts = acceptsRaw.replaceAll(USES_FILE_REF_IMPORT, "fileRefSchema")
    const returns = op.returns.replaceAll(USES_FILE_REF_IMPORT, "fileRefSchema")
    if (accepts.includes("fileRefSchema") || returns.includes("fileRefSchema")) capUsesFileRef = true
    if (hasRefs(accepts) || hasRefs(returns)) capUsesSchemas = true
    const indent = (text, pad) => text.split("\n").join(`\n${pad}`)
    capLines.push(`  ${JSON.stringify(op.name)}: capability<z.ZodType, z.ZodType>({`)
    capLines.push(`    summary: ${JSON.stringify(op.metadata.summary)},`)
    capLines.push(`    description: ${JSON.stringify(op.metadata.description)},`)
    capLines.push(`    useCases: ${JSON.stringify(op.metadata.useCases)},`)
    capLines.push(`    projections: ${JSON.stringify(op.metadata.projections)},`)
    capLines.push(`    accepts: ${indent(resolveRefs(accepts, "schemas."), "    ")},`)
    capLines.push(`    returns: ${resolveRefs(returns, "schemas.")},`)
    capLines.push(`    timeoutMs: ${op.opClass === "async-submit" ? ASYNC_TIMEOUT_MS : SYNC_TIMEOUT_MS},`)
    capLines.push(`    handler: () => import("./operations.js").then((operations) => operations.load(${JSON.stringify(op.name)})),`)
    capLines.push(`  }),`)
  }
  const capabilitiesTs = [
    `/* ${GENERATED_BANNER} */`,
    `/* Source: ${rels} */`,
    `import { capability } from "@executioncontrolprotocol/plugin-sdk"`,
    `import { z } from "zod"`,
    ...(capUsesFileRef ? [`import { fileRefSchema } from "../../schemas.js"`] : []),
    ...(capUsesSchemas ? [`import * as schemas from "./schemas.js"`] : []),
    ``,
    `/**`,
    ` * Adobe ${familyLabel(family)} capabilities. Handlers load on first call.`,
    ` * @category Generated`,
    ` */`,
    `export const ${exportName} = {`,
    ...capLines,
    `}`,
    ``,
  ].join("\n")

  const opLines = []
  let opsUseSchemas = false
  let opsUseZod = false
  for (const op of ops) {
    const p = op.built.parameters
    const params = {}
    if (p.path.length) params.path = p.path
    if (p.query.length) params.query = p.query
    if (p.headers.length) params.headers = p.headers
    if (p.body.length) params.body = p.body
    opLines.push(`  ${JSON.stringify(op.name)}: {`)
    opLines.push(`    method: ${JSON.stringify(op.method)},`)
    opLines.push(`    path: ${JSON.stringify(op.path)},`)
    opLines.push(`    serverUrl: ${JSON.stringify(op.server)},`)
    opLines.push(`    asyncMode: ${JSON.stringify(op.opClass === "async-submit" ? "submit" : "none")},`)
    if (Object.keys(params).length) opLines.push(`    parameters: ${JSON.stringify(params)},`)
    if (op.built.bodySchema) {
      const expr = op.built.bodySchema
      if (hasRefs(expr)) opsUseSchemas = true
      if (/\bz\./.test(resolveRefs(expr, ""))) opsUseZod = true
      opLines.push(`    bodySchema: ${resolveRefs(expr, "schemas.").split("\n").join("\n    ")},`)
      opLines.push(`    bodyRequired: ${op.built.bodyRequired},`)
    }
    if (op.built.defaultCaiClaimVersion) opLines.push(`    defaultCaiClaimVersion: true,`)
    if (op.defaultManifestOutputs) opLines.push(`    defaultManifestOutputs: true,`)
    if (op.productShape) opLines.push(`    productShape: ${JSON.stringify(op.productShape)},`)
    if (op.fileRefBodyFields?.length) opLines.push(`    fileRefBodyFields: ${JSON.stringify(op.fileRefBodyFields)},`)
    opLines.push(`  },`)
  }
  const operationsTs = [
    `/* ${GENERATED_BANNER} */`,
    `/* Source: ${rels} */`,
    ...(opsUseZod ? [`import { z } from "zod"`] : []),
    `import { createAdobeHandler, type AdobeHandlerModule, type AdobeOperation } from "../../runtime/invoke-capability.js"`,
    ...(opsUseSchemas ? [`import * as schemas from "./schemas.js"`] : []),
    ``,
    `/**`,
    ` * HTTP operation behind each Adobe ${familyLabel(family)} capability.`,
    ` * @category Generated`,
    ` */`,
    `export const operations: Record<string, AdobeOperation> = {`,
    ...opLines,
    `}`,
    ``,
    `/**`,
    ` * Handler module for one Adobe ${familyLabel(family)} capability. Called by the lazy`,
    ` * \`handler\` thunk in capabilities.ts.`,
    ` * @category Generated`,
    ` */`,
    `export function load(name: string): AdobeHandlerModule {`,
    `  const operation = operations[name]`,
    `  if (!operation) throw new Error(\`Unknown Adobe ${family} operation \${name}.\`)`,
    `  return { default: createAdobeHandler(name, operation) }`,
    `}`,
    ``,
  ].join("\n")

  /** @type {GeneratedOperation[]} */
  const operations = ops.map((op) => ({
    name: op.name,
    family,
    method: op.method,
    path: op.path,
    asyncMode: op.opClass === "async-submit" ? "submit" : "none",
    accepts: op.built.keys,
  }))

  const agentMetadata = ops.map((op) => ({
    name: op.name,
    summary: op.metadata.summary,
    useCases: op.metadata.useCases,
  }))

  return {
    exportName,
    files: { "schemas.ts": schemasTs, "capabilities.ts": capabilitiesTs, "operations.ts": operationsTs },
    operations,
    agentMetadata,
    skipped,
    errors: errors.map((e) => `[${family}] ${e}`),
  }
}

/**
 * Generate every family plus the registry index and meta.json.
 * @param {Map<string, FamilySpec[]>} families
 * @returns {{ files: Record<string, string>, errors: string[], meta: any }}
 */
export function generateAll(families) {
  /** @type {Record<string, string>} */
  const files = {}
  /** @type {string[]} */
  const errors = []
  const imports = []
  const spreads = []
  /** @type {GeneratedOperation[]} */
  const operations = []
  /** @type {{ name: string, reason: string }[]} */
  const skipped = []
  const specFiles = []
  /** @type {{ name: string, summary: string, useCases: string[] }[]} */
  const agentMetadata = []

  for (const [family, specs] of families) {
    const result = generateFamily(family, specs)
    for (const [file, content] of Object.entries(result.files)) files[`${family}/${file}`] = content
    errors.push(...result.errors)
    operations.push(...result.operations)
    agentMetadata.push(...result.agentMetadata)
    skipped.push(...result.skipped)
    specFiles.push(...specs.map((s) => s.rel))
    if (result.operations.length > 0) {
      imports.push(`import { ${result.exportName} } from "./${family}/capabilities.js"`)
      spreads.push(`  ...${result.exportName},`)
    }
  }

  files["index.ts"] = [
    `/* ${GENERATED_BANNER} */`,
    ...imports,
    ``,
    `/**`,
    ` * Every generated Adobe capability, keyed by capability name.`,
    ` * @category Generated`,
    ` */`,
    `export const generatedCapabilities = {`,
    ...spreads,
    `}`,
    ``,
    `/**`,
    ` * Number of generated capabilities.`,
    ` * @category Generated`,
    ` */`,
    `export const GENERATED_CAPABILITY_COUNT = ${operations.length}`,
    ``,
  ].join("\n")

  const meta = {
    pluginId: PLUGIN_ID,
    families: [...families.keys()],
    pendingFamilies: [],
    specFiles: specFiles.sort(),
    capabilityCount: operations.length,
    capabilities: operations.map((op) => ({
      name: op.name,
      family: op.family,
      method: op.method,
      path: op.path,
      asyncMode: op.asyncMode,
    })),
    skipped: skipped.sort((a, b) => (a.name < b.name ? -1 : 1)),
  }
  files["meta.json"] = `${JSON.stringify(meta, null, 2)}\n`

  agentMetadata.sort((a, b) => (a.name < b.name ? -1 : 1))
  assertAgentMetadata(agentMetadata)

  return { files, errors, meta }
}
