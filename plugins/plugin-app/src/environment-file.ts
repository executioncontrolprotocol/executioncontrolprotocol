import { existsSync } from "node:fs"
import { mkdir, writeFile } from "node:fs/promises"
import { dirname, join, resolve } from "node:path"

/** Canonical filename for the user default config file. @category App */
export const DEFAULT_CONFIG_FILENAME = "config.ecp.ts"

/**
 * Filenames searched when resolving the user default config file.
 * @category App
 */
export const USER_CONFIG_FILENAMES = [
  DEFAULT_CONFIG_FILENAME,
  "config.ecp.js",
  "config.ts",
] as const

/** Undocumented fallback names from the pre-config environment file. @category App */
export const LEGACY_ENVIRONMENT_FILENAMES = [
  "environment.ecp.ts",
  "environment.ecp.js",
  "environment.ts",
] as const

/**
 * Result of {@link ensureAppConfigPath}.
 * @category App
 */
export interface EnsuredAppConfig {
  /** Absolute path of the config file the App will show. */
  path: string
  /** True when this call wrote the starter template. */
  created: boolean
}

/**
 * Starter `config.ecp.ts` (same text as `ecp config init`).
 * Duplicated here because plugin-app must not import the CLI.
 * @category App
 */
export function configFileTemplate(): string {
  return `import { config, extension } from "@executioncontrolprotocol/core"

/**
 * Generated by \`ecp config init\`.
 * Bind plugins that need shared config or policy. Installed plugins work without a binding.
 */
export default config().with([
  // Bind plugins that need shared config or policy, for example:
  // extension("<plugin-id>"),
])
`
}

/**
 * Default path for a newly scaffolded config file.
 * @category App
 */
export function defaultConfigPath(configDir: string): string {
  return join(configDir, DEFAULT_CONFIG_FILENAME)
}

/**
 * Write the starter template. Creates the parent directory when missing.
 * @category App
 */
export async function writeConfigTemplate(path: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, configFileTemplate(), "utf8")
}

/**
 * Config path for `ecp app`: `--config` wins, else the first matching file in
 * `configDir` (`~/.ecp/config`).
 *
 * @category App
 */
export function resolveAppConfigPath(options: {
  /** `--config` flag value. */
  configFlag?: string
  /** oclif `config.configDir`. */
  configDir?: string
}): string | undefined {
  if (options.configFlag) return resolve(options.configFlag)
  if (!options.configDir) return undefined
  for (const name of [...USER_CONFIG_FILENAMES, ...LEGACY_ENVIRONMENT_FILENAMES]) {
    const candidate = join(options.configDir, name)
    if (existsSync(candidate)) return candidate
  }
  return undefined
}

/**
 * Resolve the App config file, writing the starter template when the chosen
 * path does not exist. `--config` wins; otherwise `configDir/config.ecp.ts`.
 *
 * @category App
 */
export async function ensureAppConfigPath(options: {
  /** `--config` flag value. */
  configFlag?: string
  /** oclif `config.configDir`. */
  configDir?: string
}): Promise<EnsuredAppConfig | undefined> {
  if (options.configFlag) {
    const path = resolve(options.configFlag)
    const created = !existsSync(path)
    if (created) await writeConfigTemplate(path)
    return { path, created }
  }
  if (!options.configDir) return undefined
  const existing = resolveAppConfigPath({ configDir: options.configDir })
  if (existing) return { path: existing, created: false }
  const path = defaultConfigPath(options.configDir)
  await writeConfigTemplate(path)
  return { path, created: true }
}
