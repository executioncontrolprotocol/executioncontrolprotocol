import {
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import {
  isZodType,
  jsonSchemaFromZod,
  type Registry,
} from "@executioncontrolprotocol/core"
import { defaultEcpHome, ECP_HOME_CACHE } from "./ecp-home.js"

/** Marker comment written into generated editor tsconfig files. @category CLI */
export const ECP_TSCONFIG_MARKER = "Generated by ecp workflows init --tsconfig"

/** Subdirectory under the cache root for editor types. @category CLI */
export const ECP_TYPES_CACHE_SUBDIR = "types"

/**
 * Directory for global editor types (`$ECP_CACHE_DIR/types` or `~/.ecp/cache/types`).
 * @category CLI
 */
export function ecpTypesCacheDir(
  env: NodeJS.ProcessEnv = process.env,
  home: string = defaultEcpHome()
): string {
  const cacheRoot = env.ECP_CACHE_DIR ?? join(home, ECP_HOME_CACHE)
  return join(cacheRoot, ECP_TYPES_CACHE_SUBDIR)
}

/**
 * Walk ancestors from this module for `node_modules/@executioncontrolprotocol/core`.
 * Avoids `createRequire`, which fails on packages that only declare ESM `exports`.
 */
function resolveCliCoreRoot(fromUrl: string = import.meta.url): string {
  let dir = dirname(fileURLToPath(fromUrl))
  while (true) {
    const candidate = join(dir, "node_modules", "@executioncontrolprotocol", "core")
    if (existsSync(join(candidate, "package.json"))) return candidate
    const parent = dirname(dir)
    if (parent === dir) {
      throw new Error("Could not locate @executioncontrolprotocol/core package root from the CLI")
    }
    dir = parent
  }
}

function jsonSchemaToTsProps(schema: Record<string, unknown> | undefined): {
  props: string
  wide: boolean
} {
  if (!schema) {
    return {
      props:
        '    // no input schema\n    [key: string]: import("@executioncontrolprotocol/core/types").InputValue\n',
      wide: true,
    }
  }
  const properties = schema.properties
  if (properties === null || typeof properties !== "object" || Array.isArray(properties)) {
    return {
      props:
        '    // schema could not be projected\n    [key: string]: import("@executioncontrolprotocol/core/types").InputValue\n',
      wide: true,
    }
  }
  const required = new Set(
    Array.isArray(schema.required)
      ? schema.required.filter((k): k is string => typeof k === "string")
      : []
  )
  const lines: string[] = []
  for (const key of Object.keys(properties as Record<string, unknown>)) {
    const optional = required.has(key) ? "" : "?"
    lines.push(
      `    ${JSON.stringify(key)}${optional}: import("@executioncontrolprotocol/core/types").InputValue`
    )
  }
  if (lines.length === 0) {
    return {
      props: '    [key: string]: import("@executioncontrolprotocol/core/types").InputValue\n',
      wide: true,
    }
  }
  return { props: `${lines.join("\n")}\n`, wide: false }
}

/**
 * Render `capabilities.d.ts` content from a registry.
 * @category CLI
 */
export function renderCapabilityInputsDts(registry: Registry): string {
  const caps = registry.listCapabilities().slice().sort((a, b) => a.id.localeCompare(b.id))
  const entries: string[] = []
  for (const cap of caps) {
    let schema: Record<string, unknown> | undefined
    if (cap.inputSchema) {
      if (isZodType(cap.inputSchema)) {
        schema = jsonSchemaFromZod(cap.inputSchema)
      } else if (
        cap.inputSchema !== null &&
        typeof cap.inputSchema === "object" &&
        !Array.isArray(cap.inputSchema)
      ) {
        schema = cap.inputSchema as Record<string, unknown>
      }
    }
    const { props, wide } = jsonSchemaToTsProps(schema)
    const comment = wide ? "    /** Wide input — schema could not be projected. */\n" : ""
    entries.push(`  ${JSON.stringify(cap.id)}: {\n${comment}${props}  }`)
  }
  return [
    "/* eslint-disable */",
    "/** Generated by ecp workflows types / plugins install. Do not edit. */",
    'declare module "@executioncontrolprotocol/core" {',
    "  interface CapabilityInputs {",
    entries.length > 0 ? entries.join("\n") : "    // no capabilities registered",
    "  }",
    "}",
    "",
  ].join("\n")
}

function linkCoreJunction(typesDir: string, coreRoot: string): void {
  const linkPath = join(typesDir, "core")
  rmSync(linkPath, { recursive: true, force: true })
  const type = process.platform === "win32" ? "junction" : "dir"
  symlinkSync(coreRoot, linkPath, type)
}

/**
 * Write `~/.ecp/cache/types/capabilities.d.ts` and a `core` junction to the CLI copy.
 * @category CLI
 */
export function writeGlobalCapabilityTypes(options: {
  registry: Registry
  typesDir?: string
}): { typesDir: string; capabilitiesPath: string; coreLink: string } {
  const typesDir = options.typesDir ?? ecpTypesCacheDir()
  mkdirSync(typesDir, { recursive: true })
  const capabilitiesPath = join(typesDir, "capabilities.d.ts")
  writeFileSync(capabilitiesPath, renderCapabilityInputsDts(options.registry), "utf8")
  const coreRoot = resolveCliCoreRoot()
  linkCoreJunction(typesDir, coreRoot)
  return {
    typesDir,
    capabilitiesPath,
    coreLink: join(typesDir, "core"),
  }
}

/**
 * Render an optional project `tsconfig.json` that points at the global types cache.
 * @category CLI
 */
export function renderEditorTsconfig(typesDir: string): string {
  const absTypes = resolve(typesDir)
  const absCore = join(absTypes, "core")
  const absCoreTypes = join(absCore, "dist", "types", "index.d.ts")
  const absCoreIndex = join(absCore, "dist", "index.d.ts")
  const toPath = (p: string) => p.replace(/\\/g, "/")
  return `${JSON.stringify(
    {
      compilerOptions: {
        noEmit: true,
        strict: true,
        module: "Node16",
        moduleResolution: "Node16",
        target: "ES2022",
        skipLibCheck: true,
        paths: {
          "@executioncontrolprotocol/core": [toPath(absCoreIndex)],
          "@executioncontrolprotocol/core/types": [toPath(absCoreTypes)],
        },
      },
      include: ["*.ecp.ts", "**/*.ecp.ts", toPath(join(absTypes, "capabilities.d.ts"))],
    },
    null,
    2
  )}\n`
}

/**
 * Write or refresh a generated editor `tsconfig.json`.
 * Returns `skipped` when a hand-written tsconfig without the marker is present.
 * @category CLI
 */
export function writeEditorTsconfig(options: {
  cwd?: string
  typesDir?: string
}): { path: string; status: "written" | "refreshed" | "skipped" } {
  const cwd = options.cwd ?? process.cwd()
  const typesDir = options.typesDir ?? ecpTypesCacheDir()
  const path = join(cwd, "tsconfig.json")
  const body = `// ${ECP_TSCONFIG_MARKER}\n${renderEditorTsconfig(typesDir)}`
  if (existsSync(path)) {
    const existing = readFileSync(path, "utf8")
    if (!existing.includes(ECP_TSCONFIG_MARKER)) {
      return { path, status: "skipped" }
    }
    writeFileSync(path, body, "utf8")
    return { path, status: "refreshed" }
  }
  writeFileSync(path, body, "utf8")
  return { path, status: "written" }
}
