import { access, mkdir, readFile, writeFile } from "node:fs/promises"
import { dirname, join } from "node:path"
import { ECP_INPUT_INVALID, EcpCliError, EXIT_USAGE } from "@executioncontrolprotocol/plugin-sdk"

/** Canonical filename for the user default environment file. @category CLI */
export const DEFAULT_ENVIRONMENT_FILENAME = "environment.ecp.ts"

/** Filenames searched when resolving the user default environment. @category CLI */
export const USER_ENVIRONMENT_FILENAMES = [
  DEFAULT_ENVIRONMENT_FILENAME,
  "environment.ecp.js",
  "environment.ts",
] as const

const WITH_OPEN = ".with(["

async function pathExists(path: string): Promise<boolean> {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}

/**
 * Default path for a newly scaffolded environment file.
 * @category CLI
 */
export function defaultEnvironmentPath(configDir: string): string {
  return join(configDir, DEFAULT_ENVIRONMENT_FILENAME)
}

/**
 * Starter `environment.ecp.ts` for `environments init` / `edit`.
 * @category CLI
 */
export function environmentFileTemplate(): string {
  return `import { environment, extension, NODE_ENVIRONMENT_ID } from "@executioncontrolprotocol/node"

/**
 * Generated by \`ecp environments init\`.
 * Bind plugins that need shared config or policy. Installed plugins work without a binding.
 */
export default environment(NODE_ENVIRONMENT_ID, "default").with([
  // Bind plugins that need shared config or policy, for example:
  // extension("<plugin-id>"),
])
`
}

/**
 * First existing user environment file in `configDir`, if any.
 * @category CLI
 */
export async function existingEnvironmentFile(configDir: string): Promise<string | undefined> {
  for (const name of USER_ENVIRONMENT_FILENAMES) {
    const candidate = join(configDir, name)
    if (await pathExists(candidate)) return candidate
  }
  return undefined
}

/**
 * Write the starter template. Creates the parent directory when missing.
 * @category CLI
 */
export async function writeEnvironmentTemplate(path: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, environmentFileTemplate(), "utf8")
}

/**
 * Secret-reference placeholder for a freshly installed extension id.
 * @category CLI
 */
export function secretKeyForExtension(extensionId: string): string {
  const slash = extensionId.lastIndexOf("/")
  const name = slash >= 0 ? extensionId.slice(slash + 1) : extensionId
  return `${name}/api-key`
}

/**
 * Commented `extension("id")` stub inserted into an environment file's `.with([…])`.
 * @category CLI
 */
export function extensionBindingStub(extensionId: string): string {
  const key = secretKeyForExtension(extensionId)
  return [
    `  // extension("${extensionId}"),`,
    `  // .with({`,
    `  //   apiKey: secrets("${key}"),`,
    `  // }),`,
  ].join("\n")
}

/**
 * Insert a commented extension stub after `.with([`. Idempotent when the id is already present.
 * Throws {@link ECP_INPUT_INVALID} when the file has no `.with([`.
 * @category CLI
 */
export function insertExtensionStub(
  source: string,
  extensionId: string
): { next: string; inserted: boolean } {
  if (source.includes(`"${extensionId}"`) || source.includes(`'${extensionId}'`)) {
    return { next: source, inserted: false }
  }
  const idx = source.indexOf(WITH_OPEN)
  if (idx < 0) {
    throw new EcpCliError(
      ECP_INPUT_INVALID,
      "Environment file has no .with([ bindings array to append to.",
      {
        exitCode: EXIT_USAGE,
        suggestions: ["Run ecp environments init", "Add .with([]) to the environment file"],
      }
    )
  }
  const insertAt = idx + WITH_OPEN.length
  const stub = `\n${extensionBindingStub(extensionId)}`
  return { next: `${source.slice(0, insertAt)}${stub}${source.slice(insertAt)}`, inserted: true }
}

/**
 * Append an extension stub to `path`, scaffolding the template when the file is missing.
 * @category CLI
 */
export async function appendExtensionStubToEnvFile(
  path: string,
  extensionId: string
): Promise<{ path: string; inserted: boolean }> {
  const exists = await pathExists(path)
  if (!exists) await writeEnvironmentTemplate(path)
  const source = await readFile(path, "utf8")
  const { next, inserted } = insertExtensionStub(source, extensionId)
  if (inserted) await writeFile(path, next, "utf8")
  return { path, inserted }
}
